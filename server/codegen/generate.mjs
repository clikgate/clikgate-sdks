function generate(name, lang, jar, workDir) {
  const filtered = join(workDir, 'openapi.server.json');
  writeFileSync(filtered, JSON.stringify(spec, null, 2));
  const raw = join(workDir, `raw-${name}`);
  const cmd = [
    `-Xmx${config.openapi_generator.max_heap ?? '1g'}`,
    '-jar',
    jar,
    'generate',
    '-g',
    lang.generator,
    '-i',
    filtered,
    '-t',
    join(here, lang.templates),
    '-o',
    raw,
    '--global-property',
    lang.global_property ?? 'apis,models',
    '--skip-validate-spec',
    ...Object.entries(lang.type_mappings ?? {}).flatMap(([k, v]) => ['--type-mappings', `${k}=${v}`]),
    '--additional-properties',
    Object.entries(lang.additional_properties ?? {})
      .map(([k, v]) => `${k}=${v}`)
      .join(','),
  ];
  const r = spawnSync('java', cmd, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) {
    console.error(r.stdout.slice(-4000), r.stderr.slice(-4000));
    die(`OpenAPI Generator failed for ${name}`);
  }
  return POSTPROCESS[name](raw, lang);
}

