#!/usr/bin/env node
// Regenerate the `api.*` layer and the shared enums (GoalKind, GoalStatus, Provider) of the server SDKs
// from openapi.json. One command:
//
//   node server/codegen/generate.mjs                       # regenerate from server/openapi/ (vendored)
//   node server/codegen/generate.mjs --from ../clikgate_api # copy the backend's docs/openapi-public.json (else docs/openapi.json) first
//   node server/codegen/generate.mjs --check               # CI drift check: fail if committed output differs
//   node server/codegen/generate.mjs --lang node           # one language only
//
// Needs Java 11+ (OpenAPI Generator). The pinned JAR is downloaded once to server/codegen/.cache and
// verified against generator.json's SHA-256. See server/codegen/README.md.

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { enumSources, enumValues } from './enums.mjs';
import { filterSpec, neverPublishedOperations, resourceName } from './filter.mjs';
import { applyChange22 } from './removed.mjs';
import { backendSpec, LEGACY_SPEC, PUBLIC_SPEC, vendoredSpec } from './source.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const serverDir = resolve(here, '..');
const openapiDir = join(serverDir, 'openapi');
const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const opt = (n) => {
  const i = args.indexOf(`--${n}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const config = JSON.parse(readFileSync(join(here, 'generator.json'), 'utf8'));
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const die = (msg) => {
  console.error(`generate: ${msg}`);
  process.exit(1);
};

// 1. Optional sync from the backend repository ------------------------------------------------
// Change 21 (R.41): the backend's public document `docs/openapi-public.json` (`public` + `sdk` routes), else, for a
// backend checkout from before it existed, the single `docs/openapi.json`.
const from = opt('from');
if (from) {
  const src = backendSpec(resolve(from));
  const specText = readFileSync(src.path, 'utf8');
  JSON.parse(specText);
  mkdirSync(openapiDir, { recursive: true });
  writeFileSync(join(openapiDir, src.name), specText.endsWith('\n') ? specText : `${specText}\n`);
  // Once the public document is vendored, the legacy copy would only mislead: remove it
  if (!src.fallback) rmSync(join(openapiDir, LEGACY_SPEC), { force: true });
  console.log(`Copied ${src.name} from ${resolve(from)}${src.fallback ? ` (no docs/${PUBLIC_SPEC} there yet: using the legacy file)` : ''}`);
}

// 2. Filter ------------------------------------------------------------------------------------
const source = vendoredSpec(openapiDir);
const specPath = source.path;
if (!existsSync(specPath)) die(`server/openapi/${PUBLIC_SPEC} is missing; run with --from <path to clikgate_api>`);
const specBytes = readFileSync(specPath);
const fullSpec = JSON.parse(specBytes.toString('utf8'));
// The SDKs build from the backend's PUBLIC spec only. Staff, internal and webhook routes never belong in it: the
// private openapi-staff.json / openapi-dashboard.json (and the old openapi.staff.json) must never be copied here.
// Fail (also in --check) if any staff path, staff operation or never-published audience shows up.
const staffLeaks = [
  ...Object.entries(fullSpec.paths ?? {}).flatMap(([path, item]) =>
    /^\/v1\/staff(\/|$)/.test(path)
      ? [path]
      : Object.entries(item ?? {})
          .filter(([, op]) => op && typeof op === 'object' && op['x-clikgate-auth'] === 'staff')
          .map(([m]) => `${m.toUpperCase()} ${path} (x-clikgate-auth staff)`),
  ),
  ...neverPublishedOperations(fullSpec),
];
if (staffLeaks.length) die(`server/openapi/${source.name} contains staff, internal or webhook routes (use the backend's public docs/${PUBLIC_SPEC}, never a private document):\n  ${staffLeaks.slice(0, 10).join('\n  ')}${staffLeaks.length > 10 ? `\n  … ${staffLeaks.length - 10} more` : ''}`);
// Change 22: drop the removed app-event routes and add GoalStatus `received` (removed.mjs), until the backend's
// document has caught up.
const { spec: effectiveSpec, notes: change22Notes } = applyChange22(fullSpec);
const { spec, report } = filterSpec(effectiveSpec);
const specSha = sha256(specBytes);
let enums;
try {
  enums = enumValues(effectiveSpec);
} catch (e) {
  die(e.message);
}
const reportText = [
  `# Generated by server/codegen/generate.mjs. Do not edit.`,
  `# Source ${source.name} sha256 ${specSha}${report.audiences ? ' (x-audience public only)' : ''}`,
  ...change22Notes.map((n) => `# Change 22: ${n}`),
  `# Included operations: ${report.included}; schemas: ${report.schemas}; skipped: ${report.skipped.length}`,
  ...report.skipped.map((s) => `skipped ${s}`),
  '',
].join('\n');

// 3. Generator JAR -----------------------------------------------------------------------------
function ensureJar() {
  const cache = join(here, '.cache');
  mkdirSync(cache, { recursive: true });
  const jar = join(cache, `openapi-generator-cli-${config.openapi_generator.version}.jar`);
  if (!existsSync(jar) || sha256(readFileSync(jar)) !== config.openapi_generator.sha256) {
    console.log(`Downloading OpenAPI Generator ${config.openapi_generator.version}…`);
    const r = spawnSync('curl', ['-sSfL', '-o', jar, config.openapi_generator.url], { stdio: 'inherit' });
    if (r.status !== 0) die('download failed');
    const got = sha256(readFileSync(jar));
    if (got !== config.openapi_generator.sha256) {
      rmSync(jar);
      die(`checksum mismatch for the generator JAR (got ${got})`);
    }
  }
  return jar;
}

